const HelpModalMarketingAutomation = ({ isOpen, onClose }) => {
  const [selectedTab, setSelectedTab] = useState('overview')
  const [query, setQuery] = useState('')
  const [showDetails, setShowDetails] = useState(true)
  const [activeAnchor, setActiveAnchor] = useState('')
  const contentRef = useRef(null)

  const baseSections = useMemo(() => {
    const tab = tabs.find((t) => t.id === selectedTab)
    const allowed = tab ? new Set(tab.sectionIds) : new Set()
    return sections.filter((s) => allowed.has(s.id))
  }, [selectedTab])

  const results = useMemo(() => {
    const q = normalize(query)
    if (!q) return baseSections

    return baseSections
      .map((section) => {
        const filteredItems = (section.items || []).filter((item) => {
          const searchText = `${item.title} ${item.purpose} ${(item.steps || []).join(' ')} ${(item.tips || []).join(' ')}`
          return normalize(searchText).includes(q)
        })
        return filteredItems.length
          ? { ...section, items: filteredItems.length ? filteredItems : section.items }
          : null
      })
      .filter(Boolean)
  }, [query, baseSections])

  const handleScroll = useCallback(
    (container) => {
      try {
        const base = container || contentRef.current
        if (!base) return
        const baseRect = base.getBoundingClientRect()
        const anchors = []
        results.forEach((section) => {
          ;(section.items || []).forEach((item) => {
            const id = `${section.id}-${item.id}`
            const el = base.querySelector(`#${id}`)
            if (el) {
              const top = el.getBoundingClientRect().top - baseRect.top
              anchors.push({ id, top: Math.abs(top) })
            }
          })
        })
        anchors.sort((a, b) => a.top - b.top)
        if (anchors.length) setActiveAnchor(anchors[0].id)
      } catch (err) {
        setActiveAnchor('')
      }
    },
    [results]
  )

  useEffect(() => {
    if (contentRef.current) {
      handleScroll(contentRef.current)
    }
  }, [results, handleScroll])

  if (!isOpen) return null

  return (
    <div className="modal-overlay-creat-group">
      <div className="modal-content-creat-group" style={{ maxWidth: '980px' }}>
        <AiFillCloseCircle className="modal-overlay-close-creat-group" onClick={onClose} />

        <strong className="title-creat-group">Справка: Автоматизация маркетинга</strong>
        <p style={{ opacity: 0.8, marginBottom: 8 }}>
          Подробные инструкции по созданию, управлению и отправке маркетинговых кампаний через
          Telegram.
        </p>
        <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap', margin: '6px 0 8px 0' }}>
          {tabs.map((tab) => (
            <button
              key={tab.id}
              onClick={() => setSelectedTab(tab.id)}
              style={{
                padding: '6px 10px',
                borderRadius: 8,
                border: selectedTab === tab.id ? '1px solid #0b63c5' : '1px solid rgba(0,0,0,0.1)',
                background: selectedTab === tab.id ? '#eef6ff' : '#fff',
                color: selectedTab === tab.id ? '#0b63c5' : 'inherit',
                cursor: 'pointer',
              }}
            >
              {tab.title}
            </button>
          ))}
        </div>
        <div
          style={{
            display: 'flex',
            gap: 8,
            alignItems: 'center',
            marginBottom: 8,
            flexWrap: 'wrap',
          }}
        >
          <label style={{ display: 'inline-flex', alignItems: 'center', gap: 6 }}>
            <input
              type="checkbox"
              checked={showDetails}
              onChange={(e) => setShowDetails(e.target.checked)}
              style={{ marginRight: 4 }}
            />
            Показывать детали
          </label>
          <input
            type="text"
            placeholder="Поиск по справке..."
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            style={{
              padding: '6px 10px',
              border: '1px solid rgba(0,0,0,0.1)',
              borderRadius: 6,
              flex: 1,
              minWidth: 200,
            }}
          />
        </div>
        <div
          ref={contentRef}
          style={{
            maxHeight: '70vh',
            overflowY: 'auto',
            padding: '10px',
            border: '1px solid rgba(0,0,0,0.1)',
            borderRadius: 8,
          }}
          onScroll={() => handleScroll()}
        >
          {results.length === 0 ? (
            <div style={{ padding: 20, textAlign: 'center', color: '#999' }}>
              Ничего не найдено по запросу "{query}"
            </div>
          ) : (
            results.map((section) => (
              <div key={section.id} style={{ marginBottom: 30 }}>
                <h2
                  style={{
                    fontSize: 20,
                    fontWeight: 600,
                    marginBottom: 15,
                    color: '#333',
                    borderBottom: '2px solid #0b63c5',
                    paddingBottom: 8,
                  }}
                >
                  {section.title}
                </h2>
                {(section.items || []).map((item) => {
                  const id = `${section.id}-${item.id}`
                  const isActive = activeAnchor === id
                  return (
                    <div
                      key={item.id}
                      id={id}
                      style={{
                        marginBottom: 25,
                        padding: 15,
                        background: isActive ? '#f0f7ff' : '#fff',
                        border: `1px solid ${isActive ? '#0b63c5' : '#e0e0e0'}`,
                        borderRadius: 8,
                        transition: 'all 0.2s',
                      }}
                    >
                      <h3
                        style={{
                          fontSize: 16,
                          fontWeight: 600,
                          marginBottom: 10,
                          color: '#0b63c5',
                        }}
                      >
                        {item.title}
                      </h3>
                      {showDetails && (
                        <>
                          <p style={{ marginBottom: 12, color: '#666', lineHeight: 1.6 }}>
                            {item.purpose}
                          </p>
                          {item.steps && item.steps.length > 0 && (
                            <div style={{ marginBottom: 12 }}>
                              <strong style={{ display: 'block', marginBottom: 8, color: '#333' }}>
                                Шаги/Описание:
                              </strong>
                              <ul style={{ margin: 0, paddingLeft: 20, color: '#555' }}>
                                {item.steps.map((step, idx) => (
                                  <li key={idx} style={{ marginBottom: 6, lineHeight: 1.5 }}>
                                    {step}
                                  </li>
                                ))}
                              </ul>
                            </div>
                          )}
                          {item.result && (
                            <div
                              style={{
                                marginBottom: 12,
                                padding: 10,
                                background: '#f5f5f5',
                                borderRadius: 6,
                              }}
                            >
                              <strong style={{ display: 'block', marginBottom: 4, color: '#333' }}>
                                Результат:
                              </strong>
                              <span style={{ color: '#555' }}>{item.result}</span>
                            </div>
                          )}
                          {item.tips && item.tips.length > 0 && (
                            <div style={{ marginTop: 12 }}>
                              <strong style={{ display: 'block', marginBottom: 8, color: '#333' }}>
                                💡 Советы:
                              </strong>
                              <ul style={{ margin: 0, paddingLeft: 20, color: '#555' }}>
                                {item.tips.map((tip, idx) => (
                                  <li key={idx} style={{ marginBottom: 6, lineHeight: 1.5 }}>
                                    {tip}
                                  </li>
                                ))}
                              </ul>
                            </div>
                          )}
                        </>
                      )}
                    </div>
                  )
                })}
              </div>
            ))
          )}
        </div>
      </div>
    </div>
  )
}

export default HelpModalMarketingAutomation

